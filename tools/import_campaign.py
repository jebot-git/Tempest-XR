#!/usr/bin/env python3
"""Import original wave schedules, tuning tables and bonus courses from pinned yak.s."""
import argparse,hashlib,json,re,urllib.request
from pathlib import Path
COMMIT='8b50b467ce7dd7eee475aaf5ae86804d95401ae7'
URL=f'https://raw.githubusercontent.com/mwenge/tempest2k/{COMMIT}/src/yak.s'
p=argparse.ArgumentParser();p.add_argument('--source',type=Path);a=p.parse_args()
data=a.source.read_bytes() if a.source else urllib.request.urlopen(URL,timeout=30).read()
src='\n'.join(line.split(';')[0] for line in data.decode('latin1').splitlines())
def nums(block,kind='w'):
    return [int(t.strip().replace('$','0x'),16 if '$' in t else 10)
            for m in re.finditer(rf'\bdc\.{kind}\s+([^\n]+)',block,re.I)
            for t in m[1].split(',') if t.strip()]
def table(label,kind):
    m=re.search(rf'^{label}:([^\n]*\n(?:(?!^\w+:).*(?:\n|$))*)',src,re.M)
    if not m:raise ValueError(label)
    return nums(m[1],kind)
out=['// Generated by tools/import_campaign.py; original data Jeff Minter / Atari.',
     f'// {URL}',f'// SHA256 {hashlib.sha256(data).hexdigest()}',
     '#pragma once','#include <vector>','#include <cstdint>',
     'namespace tempest {',
     'struct SpawnRule {int periodTicks,type;};',
     'struct WaveSpec {int count;std::vector<SpawnRule> spawns;};',
     'inline const std::vector<WaveSpec> campaignWaves = {']
aliases=[]
for i in range(1,101):
    m=re.search(rf'^_nw{i}:',src,re.M)
    if not m:raise ValueError(f'Missing wave {i}')
    end=re.search(r'\bdc\.w\s+-1\b',src[m.end():],re.I)
    values=nums(src[m.end():m.end()+end.end()])
    count,period,kind=values[:3];spawns=[(period,kind)]
    for k in range(3,len(values)-1,3):
        sentinel,period,kind=values[k:k+3]
        assert sentinel==0 and 0<=kind<=11 and period>0
        spawns.append((period,kind))
    out.append('    {%d,{%s}}, // wave %d' %(count+1,','.join('{%d,%d}'%v for v in spawns),i))
    if re.search(r'^_nw\d+:',src[m.end():m.end()+end.end()],re.M):aliases.append(i)
out.append('};')
for label,kind in [('fz_stuff','l'),('tz_stuff','l'),('sz_stuff','l'),('fuz_stuff','l'),('pudels','w'),('pup_stuff','w')]:
    v=table(label,kind);assert len(v)>=25
    out.append('inline const std::vector<int> %s={%s};'%(label,','.join(map(str,v))))
out.append('inline const std::vector<std::vector<uint32_t>> ringCourses={')
for i in [1,6,3,2,7,5,4,8]:
    v=table(f'course{i}','l');assert len(v)>20
    out.append('{'+','.join(str(x)+'u' for x in v)+'},')
out.append('};\ninline const std::vector<std::vector<int>> tunnelCourses={')
for label in ['tunlvl','tunlvl7','tunlvl3','tunlvl2','tunlvl4','tunlvl5','tunlvl6','tunlvl8']:
    v=table(label,'b');assert len(v)==64
    out.append('{'+','.join(map(str,v))+'},')
out.append('};\n}')
dest=Path(__file__).resolve().parents[1]/'src/campaign.hpp'
dest.write_text('\n'.join(out)+'\n')
print(f'Imported 100 source waves, tuning tables, 8 ring and 8 tunnel courses; alias waves {aliases}')
