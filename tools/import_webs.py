#!/usr/bin/env python3
"""Extract web geometry from the pinned Jaguar source; no ROM/assets required."""
import argparse
import hashlib
import pathlib
import re
import urllib.request

COMMIT = '8b50b467ce7dd7eee475aaf5ae86804d95401ae7'
URL = f'https://raw.githubusercontent.com/mwenge/tempest2k/{COMMIT}/src/yak.s'
parser = argparse.ArgumentParser()
parser.add_argument('--source', type=pathlib.Path, help='Use a local yak.s instead of downloading')
args = parser.parse_args()
data = args.source.read_bytes() if args.source else urllib.request.urlopen(URL).read()
source = data.decode('latin1')
def numbers(text):
    return [int(x.replace('$','0x'), 0) if '$' in x else int(x)
            for line in text.splitlines() if 'dc.w' in line
            for x in line.split(';')[0].split('dc.w')[1].strip().split(',')]
names = ['PLANE','V','U','CLOVER','CIRCLE','STEPS','BOWL','LINE','TRIANGLE','CROSS',
         'SQUARE','W','SINE','HEART','ARROW','STAR','WOBBLY U','LEMON','WIDE V',
         'NECK','NUT','SMALL STAR','SPIRAL','OVAL','HOOK','TINY STAR','PENTAGON',
         'BIRD','D','CURVED L','POINTER','DIAGONAL','CAT','TEARDROP','CRINKLE','KISS','C']
output = ['// Generated by tools/import_webs.py. Original web data: Jeff Minter / Atari.',
          f'// Source: {URL}', f'// yak.s SHA256: {hashlib.sha256(data).hexdigest()}',
          '#pragma once', '#include <vector>', '#include <string>',
          'struct RawWeb { const char* name; int start; bool closed; std::vector<float> xy; std::vector<int> orientations; };',
          'inline const std::vector<RawWeb> rawWebs = {']
for i, name in enumerate(names, 1):
    match = re.search(rf'^web{i}:.*?(?=^web\d+:|^\w+:)', source, re.M|re.S)
    if not match:
        raise ValueError(f'Missing web{i}')
    values = numbers(match[0])
    last, start = values[:2]
    count = last+1
    xy = values[2:2+count*2]
    closed = values[2+count*2+2] != 0
    lanes = count if closed else count-1
    # web16 has an internal w16col label before its orientation words.
    # Read only the required words so following structures are never consumed.
    needed = 2+count*2+3+lanes
    words = []
    for line in source[match.start():].splitlines():
        if 'dc.w' in line.split(';')[0]:
            words.extend(numbers(line))
        if len(words) >= needed:
            break
    orientations = words[2+count*2+3:needed]
    assert len(orientations) == lanes, f'Missing web{i} orientations'
    output.append('    {"%s", %d, %s, {%s}, {%s}},' % (name,start,str(closed).lower(),','.join(map(str,xy)),','.join(map(str,orientations))))
output += ['};', 'inline const int webOrder[] = {4,10,0,1,8,2,11,6,12,3,13,9,14,5,15,7,',
           '4,10,0,1,8,2,17,17,12,3,13,9,19,5,15,20,',
           '23,22,26,24,20,27,25,28,29,30,31,32,33,34,35,36};']
destination = pathlib.Path(__file__).resolve().parents[1]/'src'/'webs.hpp'
destination.write_text('\n'.join(output)+'\n')
print(f'Imported {len(names)} webs -> {destination}')
