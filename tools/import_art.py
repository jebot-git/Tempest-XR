#!/usr/bin/env python3
"""Import original CRY sprite sheets and all three Joby font maps, without a ROM."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import urllib.request

COMMIT = '8b50b467ce7dd7eee475aaf5ae86804d95401ae7'
BASE = f'https://raw.githubusercontent.com/mwenge/tempest2k/{COMMIT}/src/'
root = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser()
p.add_argument('--source', type=Path, help='Local tempest2k checkout')
a = p.parse_args()

def get(path):
    return (a.source / 'src' / path).read_bytes() if a.source else urllib.request.urlopen(BASE + path, timeout=30).read()

palette = json.loads((root / 'tools/cry_palette.json').read_text())
out = root / 'assets/art'
out.mkdir(parents=True, exist_ok=True)
manifest = dict(source_commit=COMMIT, palette_reference=palette['url'], atlases=[], fonts=[])
for atlas, name, width, height in [('pic','beasty3',320,200),('pic2','beasty4',320,200),('pic4','beasty6',320,128),('pic5','beasty7',320,200),('pic6','beasty8',320,200)]:
    raw = get(f'images/{name}.cry')
    assert len(raw) == width * height * 2
    pixels = bytearray()
    for value, in struct.iter_unpack('>H', raw):
        c, r, intensity = value >> 12, (value >> 8) & 15, value & 255
        pixels.extend(palette[channel][c][r] * intensity >> 8 for channel in ('blue', 'green', 'red'))
        pixels.append(255 if value else 0)
    # Top-down BITMAPV4HEADER with explicit alpha mask, readable by SDL_LoadBMP.
    dib = struct.pack('<IiiHHIIiiII', 108, width, -height, 1, 32, 3, len(pixels), 0, 0, 0, 0)
    dib += struct.pack('<IIIII', 0xff0000, 0xff00, 0xff, 0xff000000, 0x73524742) + bytes(48)
    bmp = b'BM' + struct.pack('<IHHI', 14 + len(dib) + len(pixels), 0, 0, 14 + len(dib)) + dib + pixels
    file = f'{atlas}.bmp'
    (out / file).write_bytes(bmp)
    manifest['atlases'].append(dict(file=file, width=width, height=height, sha256=hashlib.sha256(bmp).hexdigest(),
                                   source_url=BASE + f'images/{name}.cry', raw_sha256=hashlib.sha256(raw).hexdigest()))

header = ['// Generated by tools/import_art.py. Original artwork/fonts: Joby / Jeff Minter / Atari.',
          f'// Source revision {COMMIT}', '#pragma once', '#include <array>', '#include <vector>',
          '#include <string_view>', 'namespace tempest {',
          'struct RasterFont {const char* atlas;int width,height;std::vector<std::array<int,2>> glyphs;};',
          'inline const std::vector<RasterFont> sourceFonts = {']
for name, atlas in [('afont', 'pic2'), ('bfont', 'pic6'), ('cfont', 'pic')]:
    data = get(name + '.s')
    src = '\n'.join(line.split(';')[0] for line in data.decode('latin1').splitlines())
    values = [int(value, 16) for value in re.findall(r'\bdc\.l\s+\$([0-9a-fA-F]+)', src)]
    height, width = values[0] >> 16, values[0] & 65535
    glyphs = [(value & 65535, value >> 16) for value in values[1:]]
    assert len(glyphs) == 96
    assert all(0 <= x < 320 and 0 <= y < 200 for x, y in glyphs)
    header.append('{"%s",%d,%d,{%s}},' % (atlas, width, height, ','.join('{%d,%d}' % xy for xy in glyphs)))
    manifest['fonts'].append(dict(name=name, atlas=atlas, width=width, height=height,
                                 source_url=BASE + name + '.s', raw_sha256=hashlib.sha256(data).hexdigest()))
sprites = [('logo', 'pic', 1, 1, 288, 108), ('excellent', 'pic', 137, 110, 178, 44),
           ('bonus20000', 'pic', 145, 155, 169, 23), ('points2000', 'pic5', 4, 84, 197, 65), ('250', 'pic', 0, 110, 45, 44),
           ('500', 'pic', 46, 110, 44, 44), ('750', 'pic', 90, 110, 45, 44),
           ('gameover', 'pic2', 148, 21, 145, 68), ('oneup', 'pic2', 148, 0, 64, 21)]
header += ['};', 'struct RasterRect {std::string_view name,atlas;int x,y,width,height;};',
           'inline const std::vector<RasterRect> sourceSprites = {']
for name, atlas, x, y, w, h in sprites:
    header.append('{"%s","%s",%d,%d,%d,%d},' % (name, atlas, x, y, w, h))
header += ['};', 'inline const RasterRect* sourceSprite(std::string_view name){for(const auto& s:sourceSprites)if(s.name==name)return &s;return nullptr;}', '}']
(root / 'src/raster_data.hpp').write_text('\n'.join(header) + '\n')
(out / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
print('Imported five original CRY atlases, three 96-character font maps and nine sprite regions.')
